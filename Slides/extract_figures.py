"""Copy the TikZ figures of the lecture notes into Slides/figures/notes/, one file per figure.

    python Slides/extract_figures.py

Each figure environment of Lecture1-4 becomes figures/notes/L<k>-<label>.tex (the label
without its "fig:" prefix) and keeps only the drawing: \\begin{figure}, \\centering,
\\caption and \\label are removed. The slides \\input these files, so rerun this script
after changing a figure in the notes.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Slides" / "figures" / "notes"
SOURCES = {
    "L1": ROOT / "Lecture1" / "lecture1.tex",
    "L2": ROOT / "Lecture2" / "lecture2.tex",
    "L3": ROOT / "Lecture3" / "lecture3.tex",
    "L4": ROOT / "Lecture4" / "lecture4.tex",
}
FIGURE = re.compile(r"\\begin\{figure\}(\[[^\]]*\])?(.*?)\\end\{figure\}", re.S)


def skip_group(text, i):
    """Index just after the balanced {...} or [...] group that starts at text[i]."""
    open_, close = text[i], {"{": "}", "[": "]"}[text[i]]
    depth = 0
    while i < len(text):
        if text[i] == "\\":
            i += 2
            continue
        if text[i] == open_:
            depth += 1
        elif text[i] == close:
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError("unbalanced group")


def remove_command(text, name):
    """Remove every \\name[...]{...} (optional argument, one mandatory argument)."""
    while True:
        m = re.search(r"\\" + name + r"(?![A-Za-z])\s*", text)
        if not m:
            return text
        j = m.end()
        if j < len(text) and text[j] == "[":
            j = skip_group(text, j)
        if j < len(text) and text[j] == "{":
            j = skip_group(text, j)
        text = text[: m.start()] + text[j:]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    count = 0
    for prefix, path in SOURCES.items():
        source = path.read_text(encoding="utf-8")
        for m in FIGURE.finditer(source):
            body = m.group(2)
            label = re.search(r"\\label\{fig:([^}]*)\}", body)
            if not label:
                continue
            body = remove_command(body, "caption")
            body = remove_command(body, "label")
            body = body.replace("\\centering", "")
            lines = [line.rstrip() for line in body.strip("\n").splitlines()]
            while lines and not lines[-1].strip():
                lines.pop()
            name = f"{prefix}-{label.group(1)}.tex"
            header = f"% Generated by Slides/extract_figures.py from {path.relative_to(ROOT).as_posix()}; do not edit.\n"
            (OUT / name).write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
            count += 1
    print(f"wrote {count} figures to {OUT.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
